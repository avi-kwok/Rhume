// Writes lib/data/seasonIndex.generated.ts so the browser bundle statically imports the
// optional real season only when data/season-2023-24.real.json exists.

import { existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const ROOT = join(import.meta.dirname, "..");
export const REAL_SEASON_PATH = join(ROOT, "data", "season-2023-24.real.json");
const INDEX_PATH = join(ROOT, "lib", "data", "seasonIndex.generated.ts");

const HEADER = `// AUTO-GENERATED by scripts/generate-data.ts and scripts/import-real.ts. Do not edit by hand.
// Re-run \`npm run gen:data\` after adding or removing data/season-2023-24.real.json.
`;

export function writeSeasonIndex(): boolean {
  const hasReal = existsSync(REAL_SEASON_PATH);
  const body = hasReal
    ? `import real from "../../data/season-2023-24.real.json";

/** Raw real-mode season, validated by loadSeason.ts. */
export const REAL_SEASON_2023_24_RAW: unknown = real;
`
    : `/** No data/season-2023-24.real.json was present when this file was generated. */
export const REAL_SEASON_2023_24_RAW: unknown = null;
`;
  writeFileSync(INDEX_PATH, HEADER + "\n" + body);
  return hasReal;
}
